// Bundle the small, dependency-free modules so the finished site also works from file://.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const files = ['js/dialogs.js', 'js/search.js', 'js/simulation.js', 'script.js'];
const parts = [];
for (const name of files) {
  const source = (await readFile(path.join(root, name), 'utf8'))
    .replace(/^import\s+\{[^}]+\}\s+from\s+['"][^'"]+['"];\s*$/gm, '')
    .replace(/^export function /gm, 'function ');
  parts.push(`// Source: ${name}\n${source}`);
}
await writeFile(path.join(root, 'app.js'), `/* Generated by scripts/build_client.mjs. Edit js/ and script.js. */\n(() => {\n'use strict';\n${parts.join('\n\n')}\n})();\n`);
console.log('Built dependency-free browser bundle.');
